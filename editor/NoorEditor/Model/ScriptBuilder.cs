using System.Diagnostics;
using System.Text.RegularExpressions;
using NoorEditor.Interop;

namespace NoorEditor.Model;

/// <summary>
/// Compiles a project's C# scripts (ADR-008): Scripts/*.cs with a generated Scripts/Scripts.csproj
/// (an ordinary SDK project, so Visual Studio, Rider and VS Code open it), built with the .NET SDK.
/// </summary>
public static partial class ScriptBuilder
{
    public sealed record Result(bool Ok, byte[]? Assembly, byte[]? Symbols, IReadOnlyList<string> Errors, TimeSpan Took);

    /// <summary>The NoorEngine.Scripting.dll next to the editor (scripts compile against it).</summary>
    public static string ScriptingDll => Path.Combine(AppContext.BaseDirectory, "NoorEngine.Scripting.dll");

    public static string ScriptsDir(string projectRoot) => Path.Combine(projectRoot, "Scripts");

    /// <summary>True if the project has C# scripts (Scripts/**/*.cs outside bin/obj).</summary>
    public static bool HasScripts(string projectRoot)
    {
        var dir = ScriptsDir(projectRoot);
        return Directory.Exists(dir) && Directory.EnumerateFiles(dir, "*.cs", SearchOption.AllDirectories)
            .Any(f => !f.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}") &&
                      !f.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}"));
    }

    /// <summary>Writes Scripts/Scripts.csproj (and a .gitignore for its build output) if missing or stale.</summary>
    public static void EnsureProject(string projectRoot)
    {
        var dir = ScriptsDir(projectRoot);
        Directory.CreateDirectory(dir);
        var csproj = Path.Combine(dir, "Scripts.csproj");
        var text = $"""
            <Project Sdk="Microsoft.NET.Sdk">
              <!-- Generated by NoorEditor: this project's C# scripts (ADR-008). Safe to open in an IDE.
                   NoorEditor rewrites it when the NoorEngine.Scripting location changes. -->
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <Nullable>enable</Nullable>
                <ImplicitUsings>enable</ImplicitUsings>
                <AssemblyName>Scripts</AssemblyName>
                <RootNamespace>Scripts</RootNamespace>
                <DebugType>portable</DebugType>
                <NoorScriptingDll Condition="'$(NoorScriptingDll)' == ''">{ScriptingDll}</NoorScriptingDll>
              </PropertyGroup>
              <ItemGroup>
                <Reference Include="NoorEngine.Scripting">
                  <HintPath>$(NoorScriptingDll)</HintPath>
                  <Private>false</Private>
                </Reference>
              </ItemGroup>
            </Project>

            """;
        if (!File.Exists(csproj) || File.ReadAllText(csproj) != text) File.WriteAllText(csproj, text);
        var ignore = Path.Combine(dir, ".gitignore");
        if (!File.Exists(ignore)) File.WriteAllText(ignore, "bin/\nobj/\n");
    }

    /// <summary>Creates Scripts/&lt;name&gt;.cs from the template if it doesn't exist. Returns the relative path.</summary>
    public static string CreateScript(string projectRoot, string name)
    {
        EnsureProject(projectRoot);
        var relative = $"Scripts/{name}.cs";
        var full = Path.Combine(projectRoot, relative);
        if (!File.Exists(full)) File.WriteAllText(full, Template(name));
        return relative;
    }

    public static string Template(string name) => $$"""
        using System.Numerics;
        using NoorEngine;

        // {{name}}: a NoorEngine C# script. The class name must match the file name.
        // Hooks: OnStart, OnUpdate(dt), OnFixedUpdate(dt), OnLateUpdate(dt), OnDestroy,
        //        OnCollisionEnter/Exit(other), OnTriggerEnter/Exit(other).
        // Entity is the entity this script runs on; Params holds the component's params.
        // API: docs/scripting/CSHARP_API.md

        public class {{name}} : NoorScript
        {
            public override void OnStart()
            {
                Noor.Log($"{{name}} started on {Entity.Name}");
            }

            public override void OnUpdate(float dt)
            {
                // Example: turn around the vertical axis.
                // Entity.Rotate(Vector3.UnitY, 45 * dt);
            }
        }

        """;

    [GeneratedRegex(@"^(?<file>[^\(\r\n]+)\((?<line>\d+),(?<col>\d+)\): (?<kind>error|warning) (?<code>\w+): (?<msg>.*?)( \[[^\]]*\])?\r?$", RegexOptions.Multiline)]
    private static partial Regex DiagnosticLine();

    /// <summary>Builds the scripts (dotnet build). Errors come back as "Scripts/File.cs:12: CS1002: ; expected".</summary>
    public static async Task<Result> BuildAsync(string projectRoot)
    {
        var timer = Stopwatch.StartNew();
        EnsureProject(projectRoot);
        var dir = ScriptsDir(projectRoot);
        var psi = new ProcessStartInfo("dotnet", "build Scripts.csproj -c Debug -nologo -v quiet -clp:NoSummary")
        {
            WorkingDirectory = dir,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
            CreateNoWindow = true,
        };
        psi.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
        psi.Environment["DOTNET_NOLOGO"] = "1";
        string output;
        int exit;
        try
        {
            using var process = Process.Start(psi)!;
            var stdout = process.StandardOutput.ReadToEndAsync();
            var stderr = process.StandardError.ReadToEndAsync();
            await process.WaitForExitAsync();
            output = await stdout + await stderr;
            exit = process.ExitCode;
        }
        catch (System.ComponentModel.Win32Exception)
        {
            return new Result(false, null, null, ["C# scripts need the .NET 10 SDK (the `dotnet` command was not found)"], timer.Elapsed);
        }

        var errors = new List<string>();
        foreach (Match m in DiagnosticLine().Matches(output))
        {
            if (m.Groups["kind"].Value != "error") continue;
            var file = Path.GetRelativePath(projectRoot, Path.GetFullPath(Path.Combine(dir, m.Groups["file"].Value.Trim()))).Replace('\\', '/');
            var line = $"{file}:{m.Groups["line"].Value}: {m.Groups["code"].Value}: {m.Groups["msg"].Value.Trim()}";
            if (!errors.Contains(line)) errors.Add(line);
        }
        if (exit != 0 && errors.Count == 0) errors.Add(output.Trim().Length > 0 ? output.Trim() : $"dotnet build failed ({exit})");
        if (exit != 0) return new Result(false, null, null, errors, timer.Elapsed);

        var dll = Path.Combine(dir, "bin", "Debug", "net10.0", "Scripts.dll");
        var pdb = Path.ChangeExtension(dll, ".pdb");
        if (!File.Exists(dll)) return new Result(false, null, null, [$"build succeeded but {dll} is missing"], timer.Elapsed);
        return new Result(true, File.ReadAllBytes(dll), File.Exists(pdb) ? File.ReadAllBytes(pdb) : null, [], timer.Elapsed);
    }
}
